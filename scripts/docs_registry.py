"""Doc registry helpers shared by new_md.py, build_everything.py, build_corpus and self_author.

artemis_dense/docs_index.json = {"docs": [{"file", "title", "status": "built|planned|mixed|reference",
                                          "review": "approved|pending", "in_corpus": bool}]}
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def pkg(root=ROOT):
    return os.path.join(root, "artemis_dense")


def index_path(root=ROOT):
    return os.path.join(pkg(root), "docs_index.json")


def load(root=ROOT) -> dict:
    p = index_path(root)
    return json.load(open(p)) if os.path.exists(p) else {"docs": []}


def save(idx: dict, root=ROOT):
    p = index_path(root)
    tmp = p + ".tmp"
    json.dump(idx, open(tmp, "w"), indent=2)
    open(tmp, "a").write("\n")
    os.replace(tmp, p)


def register(rel_file: str, title: str, status: str = "planned", review: str = "approved",
             in_corpus: bool = True, root=ROOT) -> dict:
    idx = load(root)
    idx["docs"] = [d for d in idx["docs"] if d["file"] != rel_file]
    entry = {"file": rel_file, "title": title, "status": status, "review": review, "in_corpus": in_corpus}
    idx["docs"].append(entry)
    idx["docs"].sort(key=lambda d: d["file"].lower())
    save(idx, root)
    return entry


def build_everything(root=ROOT) -> str:
    """Concatenate every registered doc (approved or pending, flagged) into artemis_dense/everything.md."""
    idx = load(root)
    parts = ["# everything.md: all Artemis docs in one file\n",
             "Generated by `python3 scripts/build_everything.py`. Do not edit by hand.\n",
             "## Contents\n"]
    for d in idx["docs"]:
        parts.append(f"- [{d['title']}]({d['file']}) ({d['status']}, {d['review']})")
    for d in idx["docs"]:
        p = os.path.join(pkg(root), d["file"])
        if not os.path.exists(p):
            continue
        body = open(p, encoding="utf-8").read()
        parts.append(f"\n\n---\n\n<!-- file: {d['file']} -->\n\n{body.strip()}\n")
    out = os.path.join(pkg(root), "everything.md")
    open(out, "w", encoding="utf-8").write("\n".join(parts))
    return out


def title_of(path: str) -> str:
    for line in open(path, encoding="utf-8"):
        if line.startswith("# "):
            return line[2:].strip()
    return os.path.basename(path)
