def ms(vals, p=2):
    """median [min, max] over ALL seeds of the group (successful and failed)."""
    v = [x for x in vals if x is not None]
    if not v: return "n/a"
    return f"{np.median(v):.{p}e} [{min(v):.{p}e}, {max(v):.{p}e}]"


def pick(**kw):
    out = []
    for r in rows:
        if all((r[k] == v) if not isinstance(v, (list, tuple)) else (r[k] in v) for k, v in kw.items()):
            out.append(r)
    return out


def thr_cells(g):
    ok = [r for r in g if r["threshold_status"] == "reached"]
    bad = [r for r in g if r["threshold_status"] != "reached"]
    s = f"{len(ok)}/{len(g)}"
    tte = (f"{np.mean([r['first_threshold_epoch'] for r in ok]):.0f} ep / {np.mean([r['first_threshold_seconds'] for r in ok]):.1f} s"
           if ok else "— (threshold not reached)")
    fb = (f"{np.mean([r['epochs'] for r in bad]):.0f} ep / {np.mean([r['train_seconds'] for r in bad]):.1f} s"
          if bad else "— (none failed)")
    return s, tte, fb


HDR = ("| val-threshold success (runs val MSE ≤ 1e-4 / runs) | mean time-to-threshold, successful runs (epochs / s) | mean budget consumed, failed runs (epochs / s) "
       "| best val MSE | best-ckpt train MSE | val/train MSE at best (median) | test MSE | test rel L2 | test rel L2² | best epoch (median) | y-resample Δ² |")
SEP = "|" + "---|" * (HDR.count("|") - 1)


def metric_cells(g):
    s, tte, fb = thr_cells(g)
    rl = [r["test_rel_l2"] for r in g if r["test_rel_l2"] is not None]
    return (f"| {s} | {tte} | {fb} | {ms([r['best_val_mse'] for r in g])} | {ms([r['best_ckpt_train_mse'] for r in g])} "
            f"| {np.median([r['val_over_train_at_best'] for r in g]):.2f} | {ms([r['test_mse'] for r in g])} "
            f"| {ms(rl)} | {ms([x*x for x in rl])} | {np.median([r['best_epoch'] for r in g]):.0f} "
            f"| {ms([r['msq_pred_change_y_resample'] for r in g])} |")


