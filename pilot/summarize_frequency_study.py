# failure classification
def classify(r):
    c = curves[int(r["run_id"])]
    tr, va = float(c[-1, 1]), float(c[-1, 2])  # end of training (last curve point)
    if tr > 0.1:
        return "stalled optimisation (train MSE stays high)"
    if va >= 10 * tr and va > 0.01:
        return "poor generalisation (train low, val high)"
    return "other (partial fit: train ≤ 0.1, val < 10× train, 1e-4 not reached in budget)"
A("## k=8 failure classification (from end-of-training train vs val MSE on the recorded curves)\n")
A("Rule, applied mechanically to every k=8 run that did not reach the threshold, using the **end-of-training** point of the train/val curves "
  "(zero-predictor MSE ≈ 0.5 here): **stalled optimisation** = final train MSE > 0.1; **poor generalisation** = final train MSE ≤ 0.1 and final val MSE ≥ 10× train and > 0.01; "
  "**other** = partial fit: train MSE ≤ 0.1 and val < 10× train, but 1e-4 not reached within the budget. Best-checkpoint (best-val) train MSE is shown separately: for several runs the best-val "
  "checkpoint is an early, near-zero-output state (best epoch ≈ 10) even though training later drove train MSE far lower.\n")
A("| config | params | failed / runs | stalled optimisation | poor generalisation | other |"); A("|---|---|---|---|---|---|")
